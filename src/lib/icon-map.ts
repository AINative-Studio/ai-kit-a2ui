/**
 * Resolve an icon name to its component. Falls back to a question-mark
 * icon for unknown names so a bad name degrades visibly instead of
 * crashing the render.
 */
export function resolveIcon(name: string): IconComponent {
  return ICON_MAP[name] ?? QuestionMarkCircledIcon
}
